// Build-time script: reads the diagrams/ directory and generates
// src/lib/staticDemoData.ts — a TypeScript module that bundles the tutorial
// file content so the app can run as a fully static site (GitHub Pages, CDN)
// without any server or API routes.
//
// Usage: node scripts/generate-static-demo.mjs

import { readFileSync, writeFileSync, readdirSync, mkdirSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const diagramsDir = join(root, 'diagrams');
const outFile = join(root, 'src', 'lib', 'staticDemoData.ts');

// Read all .mmd and .md files from the diagrams directory.
const entries = readdirSync(diagramsDir, { withFileTypes: true });
const mmdFiles = [];
const mdFiles = [];
const fileContents = {};

for (const entry of entries) {
  if (!entry.isFile()) continue;
  const name = entry.name;
  if (/\.mmd$/i.test(name)) {
    mmdFiles.push(name);
  } else if (/\.(md|markdown)$/i.test(name)) {
    mdFiles.push(name);
  } else {
    continue;
  }
  fileContents[name] = readFileSync(join(diagramsDir, name), 'utf-8');
}

mmdFiles.sort();
mdFiles.sort();

// Generate the TypeScript module.
const lines = [
  '// AUTO-GENERATED by scripts/generate-static-demo.mjs — do not edit by hand.',
  '// Bundles the diagrams/ directory contents for static (serverless) deployment.',
  '',
  'export const STATIC_FILES: string[] = ' + JSON.stringify(mmdFiles) + ';',
  'export const STATIC_MARKDOWN_FILES: string[] = ' + JSON.stringify(mdFiles) + ';',
  'export const STATIC_FILE_CONTENTS: Record<string, string> = ' + JSON.stringify(fileContents, null, 2) + ';',
  '',
];

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, lines.join('\n'));

console.log(`Generated ${outFile}`);
console.log(`  .mmd files: ${mmdFiles.length} (${mmdFiles.join(', ') || 'none'})`);
console.log(`  .md files:  ${mdFiles.length} (${mdFiles.join(', ') || 'none'})`);
const totalBytes = Object.values(fileContents).reduce((sum, c) => sum + c.length, 0);
console.log(`  Total content: ${(totalBytes / 1024).toFixed(1)} KB`);
